import { test, expect, type Page } from "@playwright/test";
async function showSidebar(page: Page) { const menu = page.getByRole("button", { name: "Open navigation" }); if (await menu.isVisible()) await menu.click(); }
test("three independent streams, cancellation, retry, synthesis and durable history", async ({ page }) => {
  const errors: string[] = []; page.on("pageerror", e => errors.push(e.message));
  await page.goto("/");
  await expect(page.getByRole("heading", { name: /Think beyond/ })).toBeVisible();
  await expect(page.getByRole("button", { name: "Demo mode" })).toBeVisible();
  await page.screenshot({ path: `test-results/home-${test.info().project.name}.png`, fullPage: true });
  await page.getByRole("textbox", { name: "Your prompt" }).fill("Help me decide what to build next.");
  await page.getByRole("button", { name: "Send prompt" }).click();
  await expect(page.getByRole("button", { name: "Cancel Claude", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Cancel Claude", exact: true }).click();
  const claude = page.getByRole("article", { name: "Claude response", exact: true });
  await expect(claude.getByText("Response stopped.", { exact: false })).toBeVisible();
  await expect(page.getByRole("article", { name: "OpenAI response", exact: true }).getByText(/^Complete/)).toBeVisible();
  await expect(page.getByRole("article", { name: "Perplexity response", exact: true }).getByText(/^Complete/)).toBeVisible();
  await page.getByRole("button", { name: "Retry Claude", exact: true }).click();
  await expect(claude.getByText(/^Complete/)).toBeVisible();
  await page.getByLabel("Synthesis model").selectOption("claude");
  await page.getByRole("button", { name: "Synthesize", exact: true }).click();
  const synthesis = page.getByRole("article", { name: "Synthesis response", exact: true });
  await expect(synthesis.getByRole("heading", { name: "One clear direction" })).toBeVisible();
  await expect(synthesis.getByText(/^Complete/)).toBeVisible();
  await page.screenshot({ path: `test-results/responses-${test.info().project.name}.png`, fullPage: true });
  await page.reload(); await showSidebar(page);
  await page.getByRole("button", { name: "Help me decide what to build next.", exact: true }).click();
  await expect(page.getByRole("article", { name: "Synthesis response", exact: true }).getByText(/^Complete/)).toBeVisible();
  expect(errors).toEqual([]);
});
test("project context, provider selection, export and explicit missing-key errors", async ({ page }) => {
  await page.goto("/"); await showSidebar(page);
  await page.getByRole("button", { name: "New project", exact: true }).click();
  await page.getByRole("textbox", { name: "Project name" }).fill("Launch research");
  await page.getByRole("textbox", { name: "Shared context" }).fill("Audience: independent designers. Budget: two weeks.");
  await page.getByRole("button", { name: "Create project", exact: true }).click();
  await expect(page.getByRole("button", { name: "Context attached" })).toBeVisible();
  await page.getByRole("button", { name: "Claude", exact: true }).click();
  await page.getByRole("button", { name: "Perplexity", exact: true }).click();
  await page.getByRole("textbox", { name: "Your prompt" }).fill("Suggest a research plan.");
  await page.getByRole("button", { name: "Send prompt" }).click();
  await expect(page.getByRole("article", { name: "OpenAI response", exact: true }).getByText(/^Complete/)).toBeVisible();
  await expect(page.getByRole("article", { name: "Claude response", exact: true })).toHaveCount(0);
  await page.getByRole("button", { name: "Rename conversation" }).click();
  await page.getByRole("textbox", { name: "Conversation title" }).fill("Research sprint");
  await page.getByRole("button", { name: "Save title" }).click();
  const downloaded = page.waitForEvent("download"); await page.getByRole("button", { name: "Export conversation" }).click(); expect((await downloaded).suggestedFilename()).toBe("sovereign-conversation.md");
  await page.getByRole("button", { name: "Demo mode" }).click();
  await page.getByRole("button", { name: "Live", exact: true }).click();
  await page.getByRole("button", { name: "Close dialog" }).click();
  await page.getByRole("textbox", { name: "Your prompt" }).fill("Live request without a key.");
  await page.getByRole("button", { name: "Send prompt" }).click();
  await expect(page.getByRole("alert").filter({ hasText: "OPENAI_API_KEY" })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
});
